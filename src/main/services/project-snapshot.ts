import { createHash } from 'node:crypto'
import { createReadStream, createWriteStream } from 'node:fs'
import { lstat, mkdir, opendir, readFile, realpath } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { pipeline } from 'node:stream/promises'
import { Transform } from 'node:stream'
import { AGENT_BUDGET } from '../../shared/agent-budget'

export interface ProjectSnapshot {
  revision: string | null
  files: Map<string, { hash: string; text?: string }>
  complete: boolean
  issues: string[]
  durationMs: number
}

const IGNORED = new Set(['.git', '.godot', '.solar', '.genieengine', 'node_modules'])
const TEXT_SOURCE = /\.(gd|tscn|tres|godot|cfg|uid|import|gdextension|cs|gdshader|gdshaderinc)$/i

/** Content hashes, rather than timestamps, invalidate all transitive dependencies.
 * The first cache version intentionally uses the complete snapshot, including assets,
 * class declarations, UIDs, import settings and addons. No partial graph can yield a hit.
 */
export async function snapshotProject(projectPath: string, options: {
  signal?: AbortSignal
  copyTo?: string
} = {}): Promise<ProjectSnapshot> {
  const start = Date.now()
  const limits = AGENT_BUDGET.validation
  const files: ProjectSnapshot['files'] = new Map()
  const issues: string[] = []
  const root = await realpath(projectPath)
  let bytes = 0
  let sourceTextBytes = 0
  let entries = 0
  let exhausted = false
  const check = (): void => {
    options.signal?.throwIfAborted()
    if (Date.now() - start > limits.snapshotMs) { exhausted = true; throw new Error('Project snapshot exceeded its time limit.') }
  }
  const issue = (message: string): void => { if (issues.length < 20) issues.push(message) }

  const visit = async (directory: string, relativeDir: string): Promise<void> => {
    check()
    for await (const child of await opendir(directory)) {
      if (exhausted) break
      check()
      if (IGNORED.has(process.platform === 'win32' ? child.name.toLowerCase() : child.name)) continue
      if (!relativeDir && child.name === 'exports') continue // Solar-generated export output.
      const path = join(directory, child.name)
      const rel = relativeDir ? `${relativeDir}/${child.name}` : child.name
      if (++entries > limits.maxFiles) { exhausted = true; issue('Project snapshot exceeded its entry limit.'); break }
      const info = await lstat(path)
      if (info.isSymbolicLink()) { issue(`Symbolic link was not inspected: ${rel}`); continue }
      if (info.isDirectory()) { await visit(path, rel); continue }
      if (!info.isFile()) { issue(`Non-regular project entry: ${rel}`); continue }
      // Active gameplay injects app-owned files. Refuse to validate that transient state.
      if (rel === 'override.cfg' && info.size < 4096) {
        const override = await readFile(path, 'utf8')
        if (override.startsWith('; Auto-generated by Solar while the game runs.')) {
          issue('Solar gameplay is active; validate again after stopping the game.'); continue
        }
      }
      bytes += info.size
      if (bytes > limits.maxBytes) { exhausted = true; issue('Project snapshot exceeded its byte limit.'); break }
      const hash = createHash('sha256')
      const textChunks: Buffer[] = []
      const retainText = info.size <= 2 * 1024 * 1024 && TEXT_SOURCE.test(rel)
      if (TEXT_SOURCE.test(rel)) {
        sourceTextBytes += info.size
        if (!retainText || sourceTextBytes > limits.sourceTextBytes) {
          issue('Source metadata exceeded the snapshot analysis limit.'); exhausted = true; break
        }
      }
      let streamed = 0
      const digestStream = new Transform({ transform(chunk: Buffer, _encoding, callback) {
        try {
          check()
          streamed += chunk.length
          if (bytes - info.size + streamed > limits.maxBytes) throw new Error('Project file grew beyond the snapshot limit.')
          hash.update(chunk)
          if (retainText && streamed <= 2 * 1024 * 1024) textChunks.push(chunk)
          callback(null, options.copyTo ? chunk : undefined)
        } catch (error) { callback(error as Error) }
      } })
      const input = createReadStream(path)
      if (options.copyTo) {
        const target = join(options.copyTo, rel)
        await mkdir(dirname(target), { recursive: true })
        await pipeline(input, digestStream, createWriteStream(target, { flags: 'wx' }), { signal: options.signal })
      } else {
        digestStream.resume()
        await pipeline(input, digestStream, { signal: options.signal })
      }
      const after = await lstat(path)
      bytes += streamed - info.size
      if (after.size !== info.size || after.mtimeMs !== info.mtimeMs || after.ctimeMs !== info.ctimeMs) issue(`File changed while taking snapshot: ${rel}`)
      files.set(rel, { hash: hash.digest('hex'), text: retainText && streamed <= 2 * 1024 * 1024 ? Buffer.concat(textChunks).toString('utf8') : undefined })
    }
  }
  try { await visit(root, '') } catch (error) {
    options.signal?.throwIfAborted()
    issue(error instanceof Error ? error.message : 'Project snapshot could not be read.')
  }
  const complete = issues.length === 0 && !exhausted
  const digest = createHash('sha256')
  for (const [path, file] of [...files].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)) digest.update(JSON.stringify([path, file.hash]) + '\n')
  return { revision: complete ? digest.digest('hex') : null, files, complete, issues, durationMs: Date.now() - start }
}
