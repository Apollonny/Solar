export function mainGd(name: string): string {
  // GDScript uses tab indentation by convention (Godot's default).
  // The solar header block matches the format mandated in
  // resources/agent-instructions.md — the scaffold must itself comply so the
  // AI sees a live example (and so a future UI parser finds a header in every
  // file, including this one).
  return [
    '#=== solar ===',
    '# kind: other',
    '# name: Main',
    '# summary: Loads the Solar mark for the branded starter screen.',
    '# uses: none',
    '#=== /solar ===',
    'extends Node2D',
    '',
    '',
    'func _ready() -> void:',
    '\tvar mark := get_node_or_null("StarterScreen/Center/Content/Brand/Mark") as TextureRect',
    '\tif mark != null:',
    '\t\tvar image := Image.load_from_file("res://assets/ui/solar-mark.png")',
    '\t\tif image != null and not image.is_empty():',
    '\t\t\tmark.texture = ImageTexture.create_from_image(image)',
    '\t\telse:',
    '\t\t\tpush_warning("Solar brand mark could not be loaded.")',
    '\t\tvar brand_font := FontFile.new()',
    '\t\tif brand_font.load_dynamic_font("res://assets/ui/Sora-Variable.ttf") == OK:',
    '\t\t\tvar wordmark := get_node_or_null("StarterScreen/Center/Content/Brand/Wordmark") as Label',
    '\t\t\tvar headline := get_node_or_null("StarterScreen/Center/Content/Headline") as Label',
    '\t\t\tif wordmark != null:',
    '\t\t\t\twordmark.add_theme_font_override("font", brand_font)',
    '\t\t\tif headline != null:',
    '\t\t\t\theadline.add_theme_font_override("font", brand_font)',
    '\t\telse:',
    '\t\t\tpush_warning("Solar display font could not be loaded; using the default Godot font.")',
    `\tprint("${sanitize(name)} is running — built with Solar")`,
    ''
  ].join('\n')
}

